class PrescriptionsRepository {
  SupabaseClient get _db => SupabaseService.client;
  static const bucket = 'prescriptions';

  Future<List<Prescription>> list(
      {required String? branchId, String? status}) async {
    // sales -> prescriptions is the only FK between the two tables
    // (sales_prescription_id_fkey); the hint keeps PostgREST from guessing.
    // No alias is used so Prescription.fromJson's `sales` key stays stable.
    var query = _db
        .from('prescriptions')
        .select('*, sales!sales_prescription_id_fkey(id)');
    if (branchId != null) query = query.eq('branch_id', branchId);
    if (status != null) query = query.eq('status', status);
    final rows =
        await query.order('created_at', ascending: false).limit(200) as List;
    return rows
        .map((row) =>
            Prescription.fromJson(Map<String, dynamic>.from(row as Map)))
        .toList();
  }

  /// Creates the row exactly once. The id is generated by the caller so the
  /// image can be uploaded first; on upload failure no half-written row is
  /// left behind and the caller can retry safely with the same id.
  Future<Prescription> create({
    required String id,
    required String branchId,
    required String patientName,
    int? patientAge,
    required String prescriberName,
    String? prescriberLicense,
    String? facility,
    required DateTime rxDate,
    String? notes,
    String? customerId,
    String? imagePath,
  }) async {
    final payload = <String, dynamic>{
      'id': id,
      'branch_id': branchId,
      'patient_name': patientName.trim(),
      'patient_age': patientAge,
      'prescriber_name': prescriberName.trim(),
      'prescriber_license': prescriberLicense?.trim(),
      'facility': facility?.trim(),
      'rx_date': formatIsoDate(rxDate),
      'notes': notes?.trim(),
      'customer_id': customerId,
      if (imagePath != null) 'image_path': imagePath,
    };
    final row =
        await _db.from('prescriptions').insert(payload).select().single();
    return Prescription.fromJson(Map<String, dynamic>.from(row));
  }

  Future<void> cancel(String id) => _db
      .from('prescriptions')
      .update({'status': 'cancelled'})
      .eq('id', id)
      .eq('status', 'pending');

  /// POS attach flow: marks a pending prescription as dispensed by this sale.
  /// Cashier permission is enforced by the POS screen and by RLS.
  Future<void> markDispensed({
    required String id,
    required String saleId,
    required String cashierId,
  }) =>
      _db
          .from('prescriptions')
          .update({
            'status': 'dispensed',
            'sale_id': saleId,
            'dispensed_by': cashierId,
          })
          .eq('id', id)
          .eq('status', 'pending');

  /// Byte-based upload (no `dart:io`), identical on web and Android.
  Future<String> uploadImageBytes({
    required String branchId,
    required String prescriptionId,
    required Uint8List bytes,
    String? fileName,
    String? contentType,
  }) async {
    final path = prescriptionImagePath(
      branchId: branchId,
      prescriptionId: prescriptionId,
      fileName: fileName,
    );
    await _db.storage.from(bucket).uploadBinary(
          path,
          bytes,
          fileOptions: FileOptions(
            upsert: false,
            contentType: contentType ?? 'image/jpeg',
          ),
        );
    return path;
  }

  /// Signed URLs are allowed to fail loudly; the screen maps the error with
  /// [AppErrorMapper] instead of silently showing a generic snackbar.
  Future<String> signedImageUrl(String path) =>
      _db.storage.from(bucket).createSignedUrl(path, 60 * 10);
}

final prescriptionsRepositoryProvider =
    Provider<PrescriptionsRepository>((ref) => PrescriptionsRepository());

final prescriptionsProvider =
    FutureProvider.family<List<Prescription>, String?>((ref, status) async {
  if (!SupabaseService.isReady) return const <Prescription>[];
  final profile = ref.watch(authProvider).profile;
  if (profile == null) return const <Prescription>[];
  final branchId = ref.watch(branchScopeProvider);
  // A super admin with no branch selected sees every branch.
  return ref
      .read(prescriptionsRepositoryProvider)
      .list(branchId: branchId, status: status);
});
